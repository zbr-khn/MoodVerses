  static List<QuranVerse> getVersesByMood(String moodId) {
    if (moodId == 'all' || moodId.isEmpty) {
      return verses;
    }
    return verses.where((v) => v.mood.toLowerCase() == moodId.toLowerCase()).toList();
  }

  static QuranVerse? getVerseById(String id) {
    try {
      return verses.firstWhere((v) => v.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<QuranVerse> getAllVerses() => verses;
